public class day7 {
    public static void main(String[] args) {
        // logical operator in java
        boolean pass = true;
        boolean fail = false;
        System.out.println("Your are pass in exam: " + pass);
        System.out.println("Your are fail in exam: " + fail);
        System.out.println("pass && fail: " + (pass && fail));
        System.out.println("pass || fail: " + (pass || fail));
        System.out.println("!pass: " + !pass);
    }
}